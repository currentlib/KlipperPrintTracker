from pathlib import Path

from app import gcode

SAMPLE = (Path(__file__).parent / "fixtures" / "sample_tail.gcode").read_text(encoding="utf-8")


def test_real_config_block():
    config = gcode.parse_config(SAMPLE)
    assert len(config) == 587
    assert config["layer_height"] == "0.24"
    assert config["wall_loops"] == "3"
    assert config["sparse_infill_density"] == "15%"
    assert config["nozzle_temperature"] == "240,230"
    assert config["filament_flow_ratio"] == "1.067,1.05"
    assert config["print_settings_id"] == "0.24mm Draft @Creality K1C"
    assert config["printer_settings_id"] == "Creality K1C 0.4 nozzle - Timelapse"
    assert config["upward_compatible_machine"] == ""


def test_duplicate_keys_keep_last_value():
    assert gcode.parse_config(SAMPLE)["wipe_tower_x"] == "156"


def test_credentials_are_dropped():
    text = "; CONFIG_BLOCK_START\n; print_host = printer.example\n; printhost_apikey = abc\n" \
           "; layer_height = 0.2\n; CONFIG_BLOCK_END\n"
    assert gcode.parse_config(text) == {"layer_height": "0.2"}
    assert not {k for k in gcode.parse_config(SAMPLE) if "printhost" in k}


def test_no_config_block():
    assert gcode.parse_config("G1 X10\n") is None
    assert gcode.parse_config("; CONFIG_BLOCK_START\n") is None


def test_real_header():
    assert gcode.parse_slicer(SAMPLE) == ("OrcaSlicer", "2.3.2")
    assert gcode.used_filaments(SAMPLE) == [0]


def test_other_slicers():
    assert gcode.parse_slicer("; generated by PrusaSlicer 2.8.1+win64 on 2025") == ("PrusaSlicer", "2.8.1+win64")
    assert gcode.parse_slicer("; BambuStudio 02.00.03.54\n") == ("BambuStudio", "02.00.03.54")
    assert gcode.parse_slicer(";Generated with Cura_SteamEngine 5.6.0\n") == ("Cura", "5.6.0")
    assert gcode.parse_slicer("G28\n") == (None, None)


def test_preset_list():
    raw = gcode.parse_config(SAMPLE)["filament_settings_id"]
    assert gcode.split_values(raw) == ["SkyWire PETG Чорний", "LBL - Білий Флок"]
    assert gcode.split_values("Plain PLA") == ["Plain PLA"]
    assert gcode.split_values("") == []


def test_filament_value():
    assert gcode.filament_value("240,230", 1, 2) == "230"
    assert gcode.filament_value("240", 0, 1) == "240"
    assert gcode.filament_value('"a;b";"c"', 0, 2) == "a;b"
    assert gcode.filament_value("1,2,3", 0, 2) == "1,2,3"


def test_hash_ignores_key_order():
    assert gcode.config_hash({"a": "1", "b": "2"}) == gcode.config_hash({"b": "2", "a": "1"})
    assert gcode.config_hash({"a": "1"}) != gcode.config_hash({"a": "2"})
